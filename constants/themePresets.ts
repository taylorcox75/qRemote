import type { ColorTheme } from '@/services/color-theme-manager';

/**
 * Pre-made color themes (#286).
 *
 * A preset is layered ON TOP of the built-in palettes in `ThemeContext`: applying
 * one writes its `dark` and `light` colors into the stored `customColors`
 * overrides (see `colorThemeManager.applyThemePreset`), exactly as if the user
 * had picked every color by hand. The built-in `lightColors` / `darkColors` are
 * never touched, and `default` is the empty preset — applying it clears the
 * overrides, i.e. the same as the existing "reset".
 *
 * Rules for preset data:
 * - Every non-default preset defines EVERY `ColorTheme` key for BOTH modes, so
 *   its stored colors fully determine the palette (and can be compared against
 *   what's stored to tell whether it is still "selected").
 * - Picker-editable keys are 6-digit hex (the color picker only handles that).
 *   `primaryOpac` is the one rgba() — it's the translucent tint of `primary`.
 * - `onAccent` is white everywhere: several screens still hard-code white text
 *   on filled accents, so every `primary` / `error` is dark enough to carry it.
 * - Contrast (text, secondary text, accents, torrent-state colors) is enforced
 *   by `tests/utils/themePresets.test.ts`.
 */

